/*
	A finger on a string is represented by a "ball" (or rectangle for barrè) on the fret diagrams.
	Sometimes the ball is printed white, black or with a "x". We define :

	Ball structure : array of int[BALL_LEN] {string, nfret, ballShape, finger}
	ballShape = 0 : normal ball
	ballShape = 1 : circle white ball (for roots)
	ballShape = 2 : muted string (X) if fret = 0
	ballShape = 3 : muted note (X)
	ballShape = 4 : ball inside brackets
	ballShape < 0 : barrè, number of strings starting from the ball, included, towards lower strings.
*/

